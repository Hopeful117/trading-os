package com.hope.trading.broker_service.ctrader.authentication;

import com.hope.trading.broker_service.ctrader.config.CTraderSafetyProperties;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.time.ZoneId;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CyclicBarrier;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.concurrent.TimeUnit;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@Testcontainers
class CTraderRequestSafetyGuardTest {
    private static final Instant NOW = Instant.parse("2026-10-28T00:00:00Z");

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16")
            .withDatabaseName("broker_service")
            .withUsername("postgres")
            .withPassword("postgres");

    private JdbcTemplate jdbc;
    private final MutableClock clock = new MutableClock(NOW);

    @BeforeEach
    void setUp() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("DROP TABLE IF EXISTS ctrader_request_safety_event");
        jdbc.execute("DROP TABLE IF EXISTS ctrader_request_safety");
        jdbc.execute("""
                CREATE TABLE ctrader_request_safety (
                    scope VARCHAR(128) PRIMARY KEY,
                    request_day DATE NOT NULL,
                    request_count BIGINT NOT NULL,
                    alert_logged BOOLEAN NOT NULL,
                    lease_until TIMESTAMPTZ NULL,
                    lease_token VARCHAR(64) NULL,
                    last_snapshot_at TIMESTAMP WITH TIME ZONE NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE ctrader_request_safety_event (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    occurred_at TIMESTAMPTZ NOT NULL,
                    request_day DATE NOT NULL,
                    external_account_id VARCHAR(64) NULL,
                    payload_type INTEGER NOT NULL
                )
                """);
    }

    @Test
    void hardStopBlocksBeforeTheNextProviderRequest() {
        CTraderRequestSafetyGuard guard = guard(2, 1, 2);

        guard.reserveRequest("49289512", 2100);
        guard.reserveRequest("49289512", 2102);

        assertThatThrownBy(() -> guard.reserveRequest("49289512", 2104))
                .isInstanceOf(CTraderSafetyException.class)
                .hasMessage("cTrader daily request safety stop reached");
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM ctrader_request_safety_event", Long.class))
                .isEqualTo(2);
    }

    @Test
    void requestBudgetResetsAtTheNextUtcDay() {
        CTraderRequestSafetyGuard guard = guard(1, 1, 1);

        guard.reserveRequest("49289512", 2100);
        clock.advance(Duration.ofDays(1));
        guard.reserveRequest("49289512", 2100);

        assertThat(jdbc.queryForObject(
                "SELECT request_count FROM ctrader_request_safety WHERE scope = 'GLOBAL'", Long.class))
                .isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM ctrader_request_safety_event", Long.class))
                .isEqualTo(2);
    }

    @Test
    void snapshotLeaseEnforcesCooldownAndReleasesConcurrencyLock() {
        CTraderRequestSafetyGuard guard = guard(1000, 700, 800);

        try (CTraderRequestSafetyGuard.SnapshotLease ignored = guard.acquireSnapshot("49289512")) {
            assertThatThrownBy(() -> guard.acquireSnapshot("49289512"))
                    .isInstanceOf(CTraderSafetyException.class)
                    .hasMessage("cTrader snapshot blocked by cooldown or concurrent synchronization");
        }

        assertThatThrownBy(() -> guard.acquireSnapshot("49289512"))
                .isInstanceOf(CTraderSafetyException.class)
                .hasMessage("cTrader snapshot blocked by cooldown or concurrent synchronization");
    }

    @Test
    void expiredLeaseCanBeClaimedAfterAProcessFailure() {
        CTraderRequestSafetyGuard guard = guard(1000, 700, 800);
        guard.acquireSnapshot("49289512");

        clock.advance(Duration.ofMinutes(31));

        try (CTraderRequestSafetyGuard.SnapshotLease ignored = guard.acquireSnapshot("49289512")) {
            assertThat(ignored).isNotNull();
        }
    }

    @Test
    void concurrentFirstClaimsAllowOnlyOneSnapshotLease() throws Exception {
        int workers = 4;
        CyclicBarrier barrier = new CyclicBarrier(workers);
        ExecutorService executor = Executors.newFixedThreadPool(workers);
        List<Future<Boolean>> results = new ArrayList<>();
        for (int i = 0; i < workers; i++) {
            results.add(executor.submit(() -> {
                barrier.await();
                try (CTraderRequestSafetyGuard.SnapshotLease ignored = guard(1000, 700, 800)
                        .acquireSnapshot("49289512")) {
                    return true;
                } catch (CTraderSafetyException exception) {
                    return false;
                }
            }));
        }
        executor.shutdown();

        assertThat(results.stream().filter(future -> get(future)).count()).isEqualTo(1);
    }

    @Test
    void concurrentReservationsOnTheSameScopeNeverExceedTheHardStop() throws Exception {
        int workers = 12;
        int hardStop = 8;
        CyclicBarrier barrier = new CyclicBarrier(workers);
        ExecutorService executor = Executors.newFixedThreadPool(workers);
        CTraderRequestSafetyGuard guard = guard(1000, 1, hardStop);
        List<Future<Boolean>> results = new ArrayList<>();

        for (int i = 0; i < workers; i++) {
            int payloadType = 2100 + i;
            results.add(executor.submit(() -> {
                barrier.await();
                try {
                    guard.reserveRequest("49289512", payloadType);
                    return true;
                } catch (CTraderSafetyException exception) {
                    return false;
                }
            }));
        }

        executor.shutdown();
        assertThat(executor.awaitTermination(30, TimeUnit.SECONDS)).isTrue();
        assertThat(results.stream().filter(this::get).count()).isEqualTo(hardStop);
        assertThat(jdbc.queryForObject(
                "SELECT request_count FROM ctrader_request_safety WHERE scope = 'GLOBAL'", Long.class))
                .isEqualTo((long) hardStop);
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM ctrader_request_safety_event", Long.class))
                .isEqualTo((long) hardStop);
    }

    private CTraderRequestSafetyGuard guard(long budget, long alert, long hardStop) {
        return new CTraderRequestSafetyGuard(jdbc,
                new CTraderSafetyProperties(true, budget, alert, hardStop,
                        Duration.ofMinutes(20), Duration.ofMinutes(30)),
                clock);
    }

    private static final class MutableClock extends Clock {
        private Instant instant;

        private MutableClock(Instant instant) {
            this.instant = instant;
        }

        private void advance(Duration duration) {
            instant = instant.plus(duration);
        }

        @Override
        public ZoneId getZone() {
            return ZoneOffset.UTC;
        }

        @Override
        public Clock withZone(ZoneId zone) {
            return this;
        }

        @Override
        public Instant instant() {
            return instant;
        }
    }

    private boolean get(Future<Boolean> future) {
        try {
            return future.get();
        } catch (Exception exception) {
            throw new AssertionError(exception);
        }
    }
}
