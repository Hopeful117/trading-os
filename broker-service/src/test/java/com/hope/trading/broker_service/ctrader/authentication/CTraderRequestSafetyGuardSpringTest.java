package com.hope.trading.broker_service.ctrader.authentication;

import com.hope.trading.broker_service.ctrader.config.CTraderSafetyProperties;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.test.context.junit.jupiter.SpringJUnitConfig;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import javax.sql.DataSource;
import java.time.Clock;
import java.time.Duration;
import java.time.Instant;

import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.assertj.core.api.Assertions.assertThat;

@Testcontainers
@SpringJUnitConfig(CTraderRequestSafetyGuardSpringTest.TestConfig.class)
class CTraderRequestSafetyGuardSpringTest {
    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:16")
            .withDatabaseName("broker_service")
            .withUsername("postgres")
            .withPassword("postgres");

    private final JdbcTemplate jdbc;
    private final CTraderRequestSafetyGuard guard;

    @Autowired
    CTraderRequestSafetyGuardSpringTest(JdbcTemplate jdbc, CTraderRequestSafetyGuard guard) {
        this.jdbc = jdbc;
        this.guard = guard;
    }

    @BeforeEach
    void setUp() {
        jdbc.execute("DROP TABLE IF EXISTS ctrader_request_safety_event");
        jdbc.execute("DROP TABLE IF EXISTS ctrader_request_safety");
        jdbc.execute("""
                CREATE TABLE ctrader_request_safety (
                    scope VARCHAR(128) PRIMARY KEY,
                    request_day DATE NOT NULL,
                    request_count BIGINT NOT NULL,
                    alert_logged BOOLEAN NOT NULL,
                    lease_until TIMESTAMPTZ NULL,
                    lease_token VARCHAR(64) NULL,
                    last_snapshot_at TIMESTAMP WITH TIME ZONE NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE ctrader_request_safety_event (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    occurred_at TIMESTAMPTZ NOT NULL,
                    request_day DATE NOT NULL,
                    external_account_id VARCHAR(64) NULL,
                    payload_type INTEGER NOT NULL
                )
                """);
    }

    @Test
    void auditFailureRollsBackTheRequestCounterThroughTheSpringProxy() {
        jdbc.execute("DROP TABLE ctrader_request_safety_event");

        assertThatThrownBy(() -> guard.reserveRequest("49289512", 2100))
                .isInstanceOf(RuntimeException.class);

        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM ctrader_request_safety WHERE scope = 'GLOBAL'", Long.class))
                .isZero();
    }

    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement
    static class TestConfig {
        @Bean
        DataSource dataSource() {
            return new DriverManagerDataSource(
                    POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        }

        @Bean
        JdbcTemplate jdbcTemplate(DataSource dataSource) {
            return new JdbcTemplate(dataSource);
        }

        @Bean
        PlatformTransactionManager transactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }

        @Bean
        CTraderSafetyProperties cTraderSafetyProperties() {
            return new CTraderSafetyProperties(true, 1000, 700, 800,
                    Duration.ofMinutes(20), Duration.ofMinutes(30));
        }

        @Bean
        Clock clock() {
            return Clock.fixed(Instant.parse("2026-10-28T00:00:00Z"), java.time.ZoneOffset.UTC);
        }

        @Bean
        CTraderRequestSafetyGuard cTraderRequestSafetyGuard(
                JdbcTemplate jdbc,
                CTraderSafetyProperties properties,
                Clock clock) {
            return new CTraderRequestSafetyGuard(jdbc, properties, clock);
        }
    }
}
