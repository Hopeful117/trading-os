CREATE TABLE risk_profile (
    id UUID NOT NULL,
    semantic_version VARCHAR(64) NOT NULL,
    policy_id VARCHAR(160) NOT NULL,
    policy_version VARCHAR(64) NOT NULL,
    authority VARCHAR(32) NOT NULL CHECK (authority IN ('PLATFORM','BROKER','PROP_FIRM','ACCOUNT','USER','STRATEGY')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    provenance TEXT NOT NULL,
    PRIMARY KEY (id, semantic_version)
);

CREATE TABLE risk_profile_rule (
    profile_id UUID NOT NULL,
    profile_semantic_version VARCHAR(64) NOT NULL,
    rule_id VARCHAR(80) NOT NULL CHECK (rule_id IN ('MAX_POSITION_RISK','MAX_EXPOSURE','DAILY_DRAWDOWN')),
    rule_version VARCHAR(64) NOT NULL,
    category VARCHAR(32) NOT NULL CHECK (category IN ('POSITION','ACCOUNT','PORTFOLIO','PROP_FIRM','SESSION','MARKET','COMPLIANCE','CUSTOM')),
    severity VARCHAR(32) NOT NULL CHECK (severity IN ('INFO','WARNING','BLOCKING')),
    priority INTEGER NOT NULL CHECK (priority >= 0),
    maximum_ratio NUMERIC(30,12) NOT NULL CHECK (maximum_ratio > 0),
    provenance TEXT NOT NULL,
    PRIMARY KEY (profile_id, profile_semantic_version, rule_id),
    FOREIGN KEY (profile_id, profile_semantic_version)
        REFERENCES risk_profile(id, semantic_version)
);

CREATE TABLE account_risk_configuration (
    account_id UUID PRIMARY KEY REFERENCES accounts(account_id),
    broker_account_id UUID NOT NULL UNIQUE,
    risk_time_zone VARCHAR(80) NOT NULL,
    reporting_currency VARCHAR(16) NOT NULL,
    portfolio_id UUID NOT NULL UNIQUE
);

CREATE TABLE account_risk_profile_assignment (
    account_id UUID PRIMARY KEY REFERENCES accounts(account_id),
    profile_id UUID NOT NULL,
    profile_semantic_version VARCHAR(64) NOT NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL,
    provenance TEXT NOT NULL,
    FOREIGN KEY (profile_id, profile_semantic_version)
        REFERENCES risk_profile(id, semantic_version)
);

CREATE TABLE risk_day_baseline (
    version BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id UUID NOT NULL REFERENCES accounts(account_id),
    risk_day DATE NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    reporting_currency VARCHAR(16) NOT NULL,
    amount NUMERIC(30,12) NOT NULL,
    payload_schema_version INTEGER NOT NULL,
    payload TEXT NOT NULL,
    CONSTRAINT uk_risk_day_baseline UNIQUE (account_id, risk_day)
);

CREATE TABLE risk_component_snapshot (
    version BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id UUID NOT NULL,
    component_type VARCHAR(32) NOT NULL,
    source_version VARCHAR(160) NOT NULL,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    payload_schema_version INTEGER NOT NULL,
    payload TEXT NOT NULL,
    CONSTRAINT uk_risk_component_evaluation_type UNIQUE (evaluation_id, component_type)
);

CREATE TABLE risk_context_snapshot (
    version BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evaluation_id UUID NOT NULL UNIQUE,
    captured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    payload_schema_version INTEGER NOT NULL,
    payload TEXT NOT NULL
);

CREATE TABLE risk_evaluation (
    id UUID PRIMARY KEY,
    actor_id UUID NOT NULL,
    idempotency_key VARCHAR(160) NOT NULL,
    trade_plan_id UUID NOT NULL,
    trade_plan_version BIGINT NOT NULL,
    account_id UUID NOT NULL REFERENCES accounts(account_id),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(32) NOT NULL,
    decision VARCHAR(32),
    context_snapshot_version BIGINT REFERENCES risk_context_snapshot(version),
    result_schema_version INTEGER NOT NULL,
    result_payload TEXT NOT NULL,
    response_schema_version INTEGER NOT NULL,
    response_payload TEXT NOT NULL,
    CONSTRAINT uk_risk_evaluation_actor_key UNIQUE (actor_id, idempotency_key)
);
CREATE INDEX idx_risk_evaluation_plan ON risk_evaluation(trade_plan_id, trade_plan_version);
